#!/usr/bin/env python3
"""assemble_scenes.py: writes scenes.py = the show-tell kit + the original props used + scene_body.py.

The show-tell skill says to paste the kit into scenes.py, never import it, because Gate A copies only
scenes.py. This script does that pasting reproducibly. From the 25 approved original props it keeps
only the rigs this film uses, so scenes.py stays readable.

    python assemble_scenes.py            # toolkit at ../brutalist.art (or $ART_HOME)
"""
import ast
import os
import pprint
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ART = Path(os.environ.get("ART_HOME", HERE.parent / "brutalist.art"))
KIT = ART / "skills/make/show-tell/templates"

body = (HERE / "scene_body.py").read_text(encoding="utf-8")
used = sorted(set(re.findall(r'make_original\("([a-z-]+)"', body)))

orig = (KIT / "iso_originals_25.py").read_text(encoding="utf-8")
start = orig.index("_ST_ORIGINALS_25 = ") + len("_ST_ORIGINALS_25 = ")
end = orig.index("\ndef make_original")
props = ast.literal_eval(orig[start:end])
missing = [u for u in used if u not in props]
if missing:
    raise SystemExit(f"unknown props: {missing}")
factory = orig[end:]

head = ('"""scenes.py: GENERATED by assemble_scenes.py. Edit scene_body.py, not this file.\n'
        f'Kit: brutalist.art skills/make/show-tell/templates (iso_kit.py + iso_originals_25.py, props: {", ".join(used)}).\n"""\n')
kit = (KIT / "iso_kit.py").read_text(encoding="utf-8")
code = (head + kit + "\n\n# ═════════════ original props (subset; approved set 2026-10-01) ═════════════\n"
        + "_ST_ORIGINALS_25 = " + pprint.pformat({k: props[k] for k in used}, width=120, compact=True) + "\n"
        + factory + "\n" + body)
(HERE / "scenes.py").write_text(code, encoding="utf-8")
print(f"scenes.py: {len(code.splitlines())} lines; props {used}")
