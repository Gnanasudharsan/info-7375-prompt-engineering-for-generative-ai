"""Embed the recorded first-run output into scenes.py (Gate A copies only scenes.py, so nothing is read at render time).

Reads first-run/results/<date>/ (the newest dated folder, or $RESULTS) and prints a Python block:
RECORDED = {...} with the exact values the scenes typeset. Nothing is invented here: every number and verdict
comes from the saved files, and the scenes label the panel "recorded output".
"""
import json, os, pprint, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES_ROOT = HERE.parent / "first-run" / "results"


def newest():
    days = sorted(p for p in RES_ROOT.iterdir() if p.is_dir() and re.fullmatch(r"\d{4}-\d{2}-\d{2}", p.name))
    if not days:
        sys.exit("no first-run/results/<date>/ yet: run first-run/run_all.sh first")
    return days[-1]


def main():
    res = Path(os.environ["RESULTS"]) if os.environ.get("RESULTS") else newest()
    fp = json.loads((res / "first_piece.json").read_text())
    gx = json.loads((res / "gx.json").read_text())
    data = json.loads((res / "data.json").read_text())
    dbt_txt = (res / "dbt.txt").read_text()
    dbt = {}
    for status, name in re.findall(r"\b(PASS|FAIL \d+) (not_negative_trips_(?:clean|broken)_fare_amount)\b", dbt_txt):
        dbt["clean" if "clean" in name else "broken"] = {"status": status, "test": name}
    gx_ver = re.search(r"GX Core ([\d.]+)", (res / "gx.txt").read_text()).group(1)
    recorded_at = re.search(r"Recorded (\d{4}-\d{2}-\d{2} \d{2}:\d{2})", (res / "compare.txt").read_text()).group(1)
    rec = {"date": recorded_at[:10], "recorded_at": recorded_at, "results_dir": f"first-run/results/{res.name}",
           "rule": fp["rule"], "clean_pass": fp["clean_pass"], "broken_flagged": fp["broken_flagged"],
           "score": fp["score"], "false_alarms": fp["false_alarms"], "dbt": dbt, "gx": gx, "gx_version": gx_ver,
           "rows": gx["clean"]["rows"], "real": data["real_month_findings"]}
    scored = {}
    for lab in ("hand-written-baseline", "claude-round1", "claude-round2", "claude-round1-heldout", "claude-round2-heldout"):
        f = res / f"{lab}.json"
        if f.exists():
            j = json.loads(f.read_text())
            c = j["clean"]
            scored[lab] = {"types_caught": j["types_caught"], "clean_rows": c["flagged_rows"],
                           "clean_crashed": len(c.get("crashed_checks") or []), "clean_cols": len(c.get("column_failures") or []),
                           "types": {t: v["verdict"] for t, v in j["types"].items()},
                           "neg": f'{j["types"]["negative_fare"]["caught"]}/{j["types"]["negative_fare"]["planted"]}'}
    rec["scored"] = scored
    assert set(dbt) == {"clean", "broken"}, dbt
    print("# ═════ RECORDED first-run output (generated by embed_recorded.py from " + rec["results_dir"] + ") ═════")
    print("RECORDED = " + pprint.pformat(rec, width=110, sort_dicts=True))


if __name__ == "__main__":
    main()
