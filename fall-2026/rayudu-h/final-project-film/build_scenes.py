#!/usr/bin/env python3
"""build_scenes.py — writes scenes.py = the toolkit's show-tell iso kit + this reel's scene_body.py.

The kit is pasted, not imported, because Gate A copies only scenes.py into its sandbox.
Toolkit location: $ART_HOME, else ../../../brutalist.art relative to this folder.

    python3 build_scenes.py
"""
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
ART_HOME = Path(os.environ.get("ART_HOME") or (HERE / ".." / ".." / ".." / "brutalist.art")).resolve()
KIT = ART_HOME / "skills" / "make" / "show-tell" / "templates" / "iso_kit.py"

kit = KIT.read_text()
body = (HERE / "scene_body.py").read_text()
(HERE / "scenes.py").write_text(
    "# GENERATED by build_scenes.py — edit scene_body.py, not this file.\n"
    f"# Kit: {KIT.relative_to(ART_HOME.parent)}\n" + kit.rstrip() + "\n\n\n" + body)
print(f"wrote {HERE / 'scenes.py'}  (kit {KIT.name} + scene_body.py)")
