#!/usr/bin/env python3
"""build_scenes.py: assemble scenes.py for the CueGate pitch film at build time.

scenes.py = the Brutalist show-tell kit's primitives and pacing helpers, taken unmodified from the
pinned brutalist.art checkout, followed by this film's own code (scenes_film.py). The toolkit's
runner and Gate A read a single scenes.py, so the kit is assembled in rather than imported.
scenes.py is a build output: never edit it by hand and never submit it.

The kit file must match the copy at brutalist.art commit 519fcbb (sha256 below), so the line
ranges are the same ones that were reviewed.
Usage: python3 build_scenes.py               (toolkit at ../../brutalist.art or $ART_HOME)
       python3 build_scenes.py /path/to/brutalist.art
"""
import hashlib
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ART = Path(sys.argv[1] if len(sys.argv) > 1 else os.environ.get("ART_HOME") or HERE.parent.parent / "brutalist.art")
KIT = ART / "skills" / "make" / "show-tell" / "templates" / "iso_kit.py"
KIT_SHA256 = "0f47894a6b1bdd553e654192e4f410cfef14d737273a9c26b0ad41e02f2a2578"   # iso_kit.py at 519fcbb
RANGES = [(16, 118, "ISO KIT core: imports, palette, T, Iso, ease_in, check, cursor, pill"),
          (153, 163, "paper() from the writing kit"),
          (311, 338, "pacing: until(), finish()")]

data = KIT.read_bytes()
if hashlib.sha256(data).hexdigest() != KIT_SHA256:
    sys.exit(f"build_scenes.py: {KIT} does not match the pinned kit (brutalist.art 519fcbb). Check out 519fcbb.")
lines = data.decode().splitlines()
parts = ['"""\nscenes.py: GENERATED by build_scenes.py. Do not edit; do not submit.\n'
         f"Kit lines from brutalist.art@519fcbb skills/make/show-tell/templates/iso_kit.py "
         f"(sha256 {KIT_SHA256[:12]}...), then scenes_film.py.\n\"\"\""]
for a, b, what in RANGES:
    parts.append(f"# ---- kit lines {a}-{b} ({what}), verbatim ----")
    parts.append("\n".join(lines[a - 1:b]))
parts.append("# ---- scenes_film.py (written for this film) ----")
parts.append((HERE / "scenes_film.py").read_text())
(HERE / "scenes.py").write_text("\n".join(parts) + "\n")
print("wrote", HERE / "scenes.py")
